#!/usr/bin/env python3
"""Emit server/internal/protocol/layouts_gen.go from the checked-in Python layouts.

Run from the repository root: python3 scripts/gen_go_layouts.py
The generated tables are the wire contract for both supplied packet formats.
"""

import json
import struct
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from common.f1_decoder.packet_layout import PACKET_LAYOUTS_BY_FORMAT, Segment  # noqa: E402

KINDS = {
    "B": "kU8",
    "b": "kI8",
    "H": "kU16",
    "h": "kI16",
    "I": "kU32",
    "i": "kI32",
    "Q": "kU64",
    "q": "kI64",
    "f": "kF32",
    "d": "kF64",
    "s": "kStr",
}


def parse_fmt(fmt: str) -> tuple[str, int, int]:
    if fmt.endswith("s"):
        return "kStr", 1, int(fmt[:-1] or 1)
    count = ""
    for ch in fmt:
        if ch.isdigit():
            count += ch
        else:
            break
    kind = KINDS[fmt[len(count):]]
    return kind, int(count or 1), 0


def emit_segment(seg: Segment) -> str:
    fields = []
    width = 0
    for name, fmt in seg.fields.items():
        kind, count, strlen = parse_fmt(fmt)
        fields.append(f'{{name: "{name}", kind: {kind}, count: {count}, strLen: {strlen}}}')
        width += (struct.calcsize("<" + fmt))
    return (
        "\t\t{name: %s, count: %d, merge: %s, width: %d, fields: []fieldSpec{%s}},\n"
        % (json.dumps(seg.name), seg.count, "true" if seg.merge else "false", width, ", ".join(fields))
    )


def main() -> None:
    out = Path(__file__).resolve().parent.parent / "server/internal/protocol/layouts_gen.go"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// Code generated by scripts/gen_go_layouts.py. DO NOT EDIT.",
        "// Source: common/f1_decoder/packet_layout.py and supplied F1 25 / 2026 structures.",
        "",
        "package protocol",
        "",
        "var layouts = map[uint16]map[uint8][]segmentSpec{",
    ]
    sizes: dict[str, int] = {}
    for fmt in sorted(PACKET_LAYOUTS_BY_FORMAT):
        lines.append(f"\t{fmt}: {{")
        for pid in sorted(PACKET_LAYOUTS_BY_FORMAT[fmt]):
            segs = PACKET_LAYOUTS_BY_FORMAT[fmt][pid]
            lines.append(f"\t\t{pid}: {{")
            total = 29
            for seg in segs:
                lines.append(emit_segment(seg))
                width = sum(struct.calcsize("<" + f) for f in seg.fields.values())
                if seg.name != "header":
                    total += width * seg.count
            sizes[f"{fmt}/{pid}"] = total
            lines.append("\t\t},")
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("// packetSizes is the exact decoded wire size for each format and packet ID.")
    lines.append("var packetSizes = map[uint16]map[uint8]int{")
    for fmt in sorted(PACKET_LAYOUTS_BY_FORMAT):
        lines.append(f"\t{fmt}: {{")
        for pid in sorted(PACKET_LAYOUTS_BY_FORMAT[fmt]):
            lines.append(f"\t\t{pid}: {sizes[f'{fmt}/{pid}']},")
        lines.append("\t},")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(sizes)} packet layouts)")


if __name__ == "__main__":
    main()
